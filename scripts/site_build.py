@dataclass
class Page:
    """One Markdown source page and the URL it is published at."""

    src: Path
    url_path: str  # "/about/", "/404" for the not-found page
    title: str
    description: str
    updated: str
    body: str  # Markdown, placeholders resolved
    indexable: bool

    @property
    def out_dir(self) -> Path:
        return SITE / self.url_path.strip("/")

    @property
    def html_path(self) -> Path:
        return SITE / "404.html" if self.url_path == "/404" else self.out_dir / "index.html"

    @property
    def md_path(self) -> Path:
        return SITE / "404.md" if self.url_path == "/404" else self.out_dir / "index.md"

    @property
    def md_url(self) -> str:
        return "/404.md" if self.url_path == "/404" else f"{self.url_path}index.md"


def app_version() -> str:
    """The app version, read from the release script so the site never disagrees."""
    m = re.search(r'^VERSION = "([^"]+)"', BUILD_APP.read_text(), re.M)
    if not m:
        raise click.ClickException("VERSION not found in scripts/build_app.py")
    return m.group(1)


def split_front_matter(text: str) -> tuple[dict[str, str], str]:
    """`key: value` lines between two `---` lines, then the Markdown body."""
    if not text.startswith("---\n"):
        raise ValueError("page source must start with front matter")
    head, body = text[4:].split("\n---\n", 1)
    meta = {}
    for line in head.splitlines():
        key, _, value = line.partition(":")
        meta[key.strip()] = value.strip()
    return meta, body.lstrip("\n")


def load_json(name: str):
    return json.loads((SRC / name).read_text())


# ---------------------------------------------------------------- generated sections


def prose(text: str) -> str:
    """Help and tool text as literal Markdown: placeholders like `<project>` are words,
    not HTML tags (Python-Markdown's raw-HTML parsing differs across Python versions)."""
    return text.replace("<", "&lt;").replace(">", "&gt;")


def cli_section() -> str:
    """Every CLI command with its real --help text, one heading per command."""
    snap = load_json("cli-help.json")
    out = []
    for cmd in snap["commands"]:
        anchor = cmd["name"].replace(" ", "-")
        out.append(f'### mermoz {cmd["name"]} {{#{anchor}}}\n')
        out.append(f'{prose(cmd["about"])}\n')
        out.append("```text\n" + cmd["help"].rstrip() + "\n```\n")
    return "\n".join(out)


def cli_overview() -> str:
    """The top-level `mermoz --help`, verbatim."""
    return "```text\n" + load_json("cli-help.json")["root"].rstrip() + "\n```"


def mcp_tools_section() -> str:
    """Every MCP tool with its description and input parameters."""
    out = []
    for tool in load_json("mcp-tools.json")["tools"]:
        out.append(f'### {tool["name"]} {{#{tool["name"]}}}\n')
        out.append(prose(tool["description"]) + "\n")
        schema = tool.get("inputSchema", {})
        props = schema.get("properties", {})
        required = set(schema.get("required", []))
        if props:
            out.append("| parameter | type | required | notes |")
            out.append("| --- | --- | --- | --- |")
            for pname, p in props.items():
                ptype = p.get("type", "")
                if isinstance(ptype, list):
                    ptype = " or ".join(ptype)
                if ptype == "array" and "items" in p:
                    ptype = f'array of {p["items"].get("type", "")}'
                notes = prose(p.get("description", ""))
                if "default" in p:
                    notes = (notes + f' (default {p["default"]})').strip()
                out.append(f"| `{pname}` | {ptype} | {'yes' if pname in required else 'no'} | {notes} |")
            out.append("")
        else:
            out.append("No parameters.\n")
    return "\n".join(out)


def protocol_body() -> str:
    """docs/protocol.md without its own H1 (the page supplies a branded one)."""
    text = PROTOCOL.read_text()
    return re.sub(r"\A# [^\n]*\n+", "", text)


def placeholders(version: str) -> dict[str, str]:
    tools = load_json("mcp-tools.json")
    return {
        "{{cli_overview}}": cli_overview(),
        "{{cli_commands}}": cli_section(),
        "{{mcp_tools}}": mcp_tools_section(),
        "{{mcp_tool_count}}": str(len(tools["tools"])),
        "{{mcp_protocol_version}}": tools["protocolVersion"],
        "{{protocol}}": protocol_body(),
        "{{version}}": version,
        "{{download_url}}": DOWNLOAD_URL,
        "{{bundled_cli}}": BUNDLED_CLI,
        "{{contact_email}}": CONTACT_EMAIL,
        "{{repo_url}}": REPO_URL,
    }


def load_pages(version: str) -> list[Page]:
    subs = placeholders(version)
    pages = []
    for src in sorted(PAGES.rglob("*.md")):
        meta, body = split_front_matter(src.read_text())
        for key, value in subs.items():
            body = body.replace(key, value)
        pages.append(
            Page(
                src=src,
                url_path=meta["path"],
                title=meta["title"],
                description=meta["description"],
                updated=meta["updated"],
                body=body,
                indexable=meta.get("index", "yes") == "yes",
            )
        )
    return pages


# ---------------------------------------------------------------- HTML


def render_markdown(body: str) -> str:
    md = markdown.Markdown(extensions=["tables", "fenced_code", "toc", "attr_list"])
    out = md.convert(body)
    # Escaped pipes keep table cells apart in the source; readers want the plain pipe.
    out = out.replace("\\|", "|")
    # Wide tables scroll inside the card instead of widening the page on phones.
    out = out.replace("<table>", '<div class="table-wrap"><table>').replace("</table>", "</table></div>")
    return out


