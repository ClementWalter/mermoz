"""Build the agent-facing files of mermoz.xyz from one set of Markdown sources.

Sources (site/src): one Markdown page per URL with a small front matter, plus two
snapshots of the real tool surface taken from a built `mermoz` binary
(cli-help.json, mcp-tools.json). docs/protocol.md feeds the protocol page.

Outputs, all committed so GitHub Pages publishes them as plain files:

- an HTML page and its Markdown twin for each URL (`/about/` → about/index.html and
  about/index.md), 404.html and 404.md;
- sitemap.xml, robots.txt, llms.txt, llms-full.txt;
- server.json (MCP registry format) and .well-known/mcp.json (local stdio server);
- the JSON-LD block of the hand-written homepage (between its jsonld markers).

The Cloudflare Worker in site/edge serves the Markdown twins to clients whose Accept
header prefers text/markdown.

Usage:
  scripts/site_build.py build                      # regenerate everything
  scripts/site_build.py build --check              # fail if anything is stale (CI)
  scripts/site_build.py snapshot --mermoz target/release/mermoz
                                                   # refresh the CLI/MCP snapshots
"""

