def inject_jsonld(index_html: str, version: str) -> str:
    pattern = re.compile(re.escape(JSONLD_START) + r".*?" + re.escape(JSONLD_END), re.S)
    if not pattern.search(index_html):
        raise click.ClickException("index.html lacks the jsonld markers")
    return pattern.sub(lambda _: homepage_jsonld(version), index_html)


# ---------------------------------------------------------------- build


def outputs() -> dict[Path, str]:
    """Every generated file and its content."""
    version = app_version()
    pages = load_pages(version)
    files: dict[Path, str] = {}
    homepage = next(p for p in pages if p.url_path == "/")
    for p in pages:
        files[p.md_path] = page_markdown(p)
        if p.url_path != "/":  # the homepage HTML is hand-written
            files[p.html_path] = page_html(p)
    files[SITE / "index.html"] = inject_jsonld((SITE / "index.html").read_text(), version)
    files[SITE / "sitemap.xml"] = sitemap(pages)
    files[SITE / "robots.txt"] = robots()
    files[SITE / "llms.txt"] = llms_txt(version)
    files[SITE / "llms-full.txt"] = llms_full(pages, page_markdown(homepage))
    files[SITE / "server.json"] = json.dumps(server_json(version), indent=2) + "\n"
    files[SITE / ".well-known" / "mcp.json"] = json.dumps(well_known_mcp(version), indent=2) + "\n"
    return files


@click.group()
def cli() -> None:
    logging.basicConfig(level=logging.INFO, format="%(message)s")


@cli.command()
@click.option("--check", is_flag=True, help="Fail if a generated file differs from the sources.")
def build(check: bool) -> None:
    """Regenerate the site's pages, Markdown twins and discovery files."""
    stale = []
    for path, content in outputs().items():
        current = path.read_text() if path.exists() else None
        if current == content:
            continue
        stale.append(path.relative_to(REPO))
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if check and stale:
        for p in stale:
            log.error("stale: %s", p)
        raise SystemExit("generated site files are stale: run scripts/site_build.py build")
    log.info("%s %d file(s)", "stale" if check else "wrote", len(stale))


def run_help(binary: str, args: list[str]) -> str:
    return subprocess.run([binary, *args, "--help"], check=True, capture_output=True, text=True).stdout


def subcommands(help_text: str) -> list[tuple[str, str]]:
    """(name, one-line about) pairs from clap's `Commands:` block, `help` left out."""
    block = help_text.split("Commands:\n", 1)[1].split("\n\n", 1)[0]
    pairs = []
    for line in block.splitlines():
        m = re.match(r"^  (\S+)\s+(.*)$", line)
        if m and m.group(1) != "help":
            pairs.append((m.group(1), m.group(2).strip()))
    return pairs


@cli.command()
@click.option("--mermoz", "binary", required=True, help="Path to a built mermoz binary (release).")
def snapshot(binary: str) -> None:
    """Record the real CLI help and MCP tool list from a built binary."""
    root = subprocess.run([binary, "--help"], check=True, capture_output=True, text=True).stdout
    commands = []
    for name, about in subcommands(root):
        text = run_help(binary, [name])
        commands.append({"name": name, "about": about, "help": text})
        if "Commands:\n" in text:
            for sub, sub_about in subcommands(text):
                commands.append(
                    {"name": f"{name} {sub}", "about": sub_about, "help": run_help(binary, [name, sub])}
                )
    (SRC / "cli-help.json").write_text(json.dumps({"root": root, "commands": commands}, indent=2) + "\n")

    requests = [
        {"jsonrpc": "2.0", "id": 1, "method": "initialize", "params": {"protocolVersion": "2025-06-18", "capabilities": {}, "clientInfo": {"name": "site_build", "version": "0"}}},
        {"jsonrpc": "2.0", "id": 2, "method": "tools/list"},
    ]
    stdin = "".join(json.dumps(r) + "\n" for r in requests)
    out = subprocess.run([binary, "mcp"], input=stdin, check=True, capture_output=True, text=True).stdout
    replies = [json.loads(line) for line in out.splitlines() if line.strip()]
    init, listed = replies[0]["result"], replies[1]["result"]
    snap = {
        "serverInfo": {"name": init["serverInfo"]["name"]},
        "protocolVersion": init["protocolVersion"],
        "instructions": init.get("instructions", ""),
        "tools": listed["tools"],
    }
    (SRC / "mcp-tools.json").write_text(json.dumps(snap, indent=2, ensure_ascii=False) + "\n")
    log.info("recorded %d CLI commands and %d MCP tools", len(commands), len(snap["tools"]))


if __name__ == "__main__":
    sys.exit(cli())
