def llms_full(pages: list[Page], homepage_md: str) -> str:
    parts = [f"# Mermoz: full site text\n\nSource: {HOST}/llms.txt. Each section below is one page of {HOST}.\n"]
    parts.append(homepage_md.rstrip())
    order = ["/docs/", "/docs/cli/", "/docs/mcp/", "/docs/protocol/", "/about/", "/contact/", "/privacy/"]
    by_path = {p.url_path: p for p in pages}
    for path in order:
        parts.append(page_markdown(by_path[path]).rstrip())
    return "\n\n---\n\n".join(parts) + "\n"


